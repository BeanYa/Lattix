import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const sourcePath = resolve(root, '../../docs/openapi.yaml')
const outputPath = resolve(root, 'src/lib/api-contract.generated.ts')
const source = await readFile(sourcePath, 'utf8')

const codeSection = source.match(/    RPCCode:\r?\n([\s\S]*?)    RPCEnvelope:/)?.[1]
if (!codeSection) throw new Error('OpenAPI RPCCode schema was not found')
const codes = [...codeSection.matchAll(/^        - ([A-Z][A-Z0-9_]*)$/gm)].map((match) => match[1])
if (codes.length === 0) throw new Error('OpenAPI RPCCode enum is empty')

const operations = []
const lines = source.split(/\r?\n/)
let currentPath = ''
let currentMethod = ''
for (const line of lines) {
  const path = line.match(/^  (\/api\/[^:]+):$/)
  if (path) {
    currentPath = path[1]
    currentMethod = ''
    continue
  }
  const method = line.match(/^    (get|post):$/)
  if (method && currentPath) {
    currentMethod = method[1].toUpperCase()
    continue
  }
  const operation = line.match(/^      operationId: ([A-Za-z][A-Za-z0-9]*)$/)
  if (operation && currentPath && currentMethod) {
    operations.push([operation[1], currentMethod, currentPath])
  }
}
if (operations.length === 0) throw new Error('OpenAPI operations were not found')

const generated = `// Generated by scripts/generate-api-types.mjs from docs/openapi.yaml.
// Do not edit manually.

export type RPCCode =
${codes.map((code) => `  | '${code}'`).join('\n')}

export interface RPCEnvelope<T = unknown> {
  code: RPCCode
  message: string
  data: T
  request_id: string
  trace_id: string
}

export const rpcOperations = {
${operations.map(([id, method, path]) => `  ${id}: { method: '${method}', path: '${path}' },`).join('\n')}
} as const
`

if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '')
  if (existing.replace(/\r\n/g, '\n') !== generated) {
    console.error('Generated API types are stale. Run: bun run generate:api')
    process.exitCode = 1
  }
} else {
  await writeFile(outputPath, generated)
}
